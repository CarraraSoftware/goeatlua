package main

import (
	"fmt"
	"bytes"
	"os"
)


// @NOTE: if your C code needs specfic linker flags for compiling correctly,
//        those flags should be in the very first line of your Go file that contains
//        the '//go:generate' directive.
// @TODO: change this flaming pile of horse shit of a convention
		

func main() {
	gofilename := os.Getenv("GOFILE");

	if gofilename == "" {
		fmt.Printf("[ERROR] Invalid go file name.\n")
		os.Exit(1)
	}

	buffer, err := os.ReadFile(gofilename);
	if err != nil {
		fmt.Printf("[ERROR] Failed to read file '%s': %s.\n", gofilename, err)
		os.Exit(1)
	}

	tail_idx := 0
	packagename := ""

	flags := ""


	dontedit_msg := 
	"////////////////////////////////////////////////////////////////////////////////\n" +
	"// CODE GENERATED BY C IMPORTER. DO NOT EDIT.                                 //\n" +
	"////////////////////////////////////////////////////////////////////////////////\n\n"

	i := 0
	for line := range bytes.Lines(buffer) {
        if i == 0 {
			flags = string(line)
		}
		i += 1

		tail_idx += len(line)
		l := bytes.TrimSpace(line)
		if bytes.HasPrefix(l, []byte("package")) {
			fields := bytes.Fields(l)
            if len(fields) < 2 {
				fmt.Printf("[ERROR]  Invalid Go File. Wrong format for package name declaration. Expected ```package <package_name>```\n")
				os.Exit(1)
			}
			name := bytes.TrimSpace(fields[1])
			packagename = string(name)
			break
		}
	}

    if packagename == "" {
		fmt.Printf("[ERROR]  Invalid Go File. Missing package name.\n")
		os.Exit(1)
	}

	head := buffer[0:tail_idx]
	tail := buffer[tail_idx:]


    if len(os.Args) < 2 {
		fmt.Printf("[ERROR] Missing file name to embed.\n")
		fmt.Printf("[ERROR] Usage:\n")
		fmt.Printf("[ERROR] 	go run c_importer.go <filename>\n")
		os.Exit(1)
	}

	cfilename := os.Args[1]
	cbuffer, err :=  os.ReadFile(cfilename);
	if err != nil {
		fmt.Printf("[ERROR] Failed to read file '%s': %s.\n", cfilename, err)
		os.Exit(1)
	}

	fmt.Printf("%s\n\n", dontedit_msg)
	fmt.Printf("%.*s\n", len(head), head);
	fmt.Printf("%s", flags);
	fmt.Printf("/*\n");
	fmt.Printf("%.*s\n", len(cbuffer), cbuffer);
	fmt.Printf("*/\n");
	fmt.Printf("import \"C\"\n");
	fmt.Printf("%.*s\n", len(tail), tail);
}
